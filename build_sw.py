"""
Cataract Screening Project - Generate the Offline Service Worker
-----------------------------------------------------------------
Writes web/sw.js: a service worker that saves every file the app needs on the phone at the
first visit (about 30 MB) and serves them from there, so the scanner and the help page work
without internet afterwards.

The cache name is a hash of all saved files, so any change to the app produces a new cache;
phones pick it up on their next visit and delete the old one. Run this before every release:

    python web/build_sw.py
"""

import hashlib
from pathlib import Path

WEB = Path(__file__).resolve().parent

# Everything the scanner and the help page load. Not included: build/test scripts, the
# reference data, and MediaPipe's no-SIMD engine (only very old phones need it; they fetch it
# online on demand).
PRECACHE = [
    "./", "index.html", "help.html", "app.js", "vision.js", "i18n.js", "theme.js", "style.css",
    "manifest.webmanifest", "icon.svg", "icon-180.png", "icon-512.png",
    "model/cataract.onnx", "model/config.json",
    "vendor/ort/ort.wasm.min.js", "vendor/ort/ort-wasm-simd-threaded.mjs", "vendor/ort/ort-wasm-simd-threaded.wasm",
    "vendor/mediapipe/vision_bundle.mjs", "vendor/mediapipe/face_landmarker.task",
    "vendor/mediapipe/wasm/vision_wasm_internal.js", "vendor/mediapipe/wasm/vision_wasm_internal.wasm",
    "vendor/fonts/fonts.css",
]
PRECACHE += sorted(f"ill/{p.name}" for p in (WEB / "ill").glob("*.jpg"))
PRECACHE += sorted(f"vendor/fonts/{p.name}" for p in (WEB / "vendor/fonts").glob("*.woff2"))

TEMPLATE = '''// Generated by web/build_sw.py - do not edit by hand.
// Saves the whole app on the phone at the first visit, then serves it from there (works offline).
const CACHE = "cataract-__VERSION__";
const PRECACHE = __FILES__;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith("cataract-") && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // files are saved without their ?v= version suffix
    const saved = await cache.match(request, { ignoreSearch: true });
    if (saved) return saved;
    try {
      return await fetch(request);
    } catch (error) {
      if (request.mode === "navigate") return (await cache.match("index.html")) || Response.error();
      throw error;
    }
  })());
});
'''


def main():
    digest = hashlib.sha256()
    total = 0
    for rel in PRECACHE:
        path = WEB / ("index.html" if rel == "./" else rel)
        data = path.read_bytes()            # fails loudly if a listed file is missing
        digest.update(rel.encode() + b"\0" + data)
        total += len(data) if rel != "./" else 0
    version = digest.hexdigest()[:12]
    files = "[\n  " + ",\n  ".join(f'"{f}"' for f in PRECACHE) + ",\n]"
    (WEB / "sw.js").write_text(TEMPLATE.replace("__VERSION__", version).replace("__FILES__", files), encoding="utf-8")
    print(f"web/sw.js written: {len(PRECACHE)} files, {total / 1e6:.1f} MB, cache cataract-{version}")


if __name__ == "__main__":
    main()
